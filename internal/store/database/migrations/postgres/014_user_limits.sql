-- A Plex account the bound server is shared with signs in as pending until an
-- admin approves it. Each user may override the global render limits, where
-- NULL takes the global value. A clip records the bytes its files take, and
-- every render a user starts is logged, in Unix seconds, for the rolling
-- weekly limit.
ALTER TABLE users ADD COLUMN approved INTEGER NOT NULL DEFAULT 1;
ALTER TABLE users ADD COLUMN limit_active INTEGER;
ALTER TABLE users ADD COLUMN limit_weekly INTEGER;
ALTER TABLE users ADD COLUMN limit_storage_bytes BIGINT;
ALTER TABLE users ADD COLUMN limit_clip_seconds INTEGER;
ALTER TABLE clips ADD COLUMN output_bytes BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS render_log (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	owner_id BIGINT NOT NULL,
	rendered_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_render_log_owner ON render_log(owner_id, rendered_at);
